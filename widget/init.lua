local SERVER_URL = "http://127.0.0.1:8765"
local logger = hs.logger.new("concise", "info")
local log = function(msg) logger.i(msg) end

-- Password managers mark secrets with these types and clear them later; rewriting the clipboard would defeat that.
local CONCEALED = {"org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"}

local copyTimer
local copying = false

local function clipboardIsConcealed(data)
  for _, uti in ipairs(CONCEALED) do
    if data[uti] ~= nil then return true end
  end
  return false
end

-- Cmd+C is ignored while Ctrl/Option are still held, so poll (without blocking) until they are released.
local function whenModifiersUp(fn)
  local tries = 0
  copyTimer = hs.timer.doEvery(0.02, function()
    tries = tries + 1
    local mods = hs.eventtap.checkKeyboardModifiers()
    if not (mods.ctrl or mods.alt) or tries >= 50 then
      copyTimer:stop()
      fn(tries * 0.02)
    end
  end)
  copyTimer:fire()
end

local function postCopy(callback, waited)
  local saved = hs.pasteboard.readAllData() or {}
  if clipboardIsConcealed(saved) then
    log("copy: skipped, clipboard holds concealed data")
    hs.alert.show("Clipboard holds a password; not touching it")
    copying = false
    return
  end
  local before = hs.pasteboard.changeCount()
  local frontApp = hs.application.frontmostApplication()
  log(string.format("copy: app=%s waited=%.2f changeCount=%d", frontApp and frontApp:name() or "?", waited, before))
  local down = hs.eventtap.event.newKeyEvent("c", true)
  down:setFlags({cmd = true})
  down:post()
  local up = hs.eventtap.event.newKeyEvent("c", false)
  up:setFlags({cmd = true})
  up:post()

  local tries = 0
  copyTimer = hs.timer.doEvery(0.05, function()
    tries = tries + 1
    if hs.pasteboard.changeCount() ~= before or tries >= 20 then
      copyTimer:stop()
      local changed = hs.pasteboard.changeCount() ~= before
      local text = hs.pasteboard.getContents()
      log(string.format("after %d tries: changed=%s textlen=%d", tries, tostring(changed), text and #text or -1))
      if changed then
        if next(saved) then hs.pasteboard.writeAllData(saved) else hs.pasteboard.clearContents() end
      end
      copying = false
      callback(changed and text or nil)
    end
  end)
end

-- A second press while copying is ignored, so the saved clipboard is always restored.
local function copySelection(callback)
  if copying then return end
  copying = true
  whenModifiersUp(function(waited) postCopy(callback, waited) end)
end

local function showScore(r)
  hs.alert.show(string.format("%.2f  %s", r.score, r.good and "✓ concise" or "✗ wordy"), 2)
end

-- onDown is called instead of alerting when the server can't be reached (status < 0).
local function postSentence(text, onResult, onDown)
  hs.http.asyncPost(SERVER_URL, text, {["Content-Type"] = "text/plain; charset=utf-8"}, function(code, body)
    if code < 0 then
      if onDown then onDown() else hs.alert.show("concise server not running") end
      return
    end
    local ok, r = pcall(hs.json.decode, body)
    if code ~= 200 or not ok or type(r) ~= "table" or type(r.score) ~= "number" then
      logger.w(string.format("server error %d", code))
      hs.alert.show("concise server error " .. code)
      return
    end
    onResult(r)
  end)
end

local function score()
  copySelection(function(text)
    if not text or text == "" then
      hs.alert.show("Select a sentence first")
      return
    end
    postSentence(text, showScore)
  end)
end

hs.hotkey.bind({"ctrl", "alt"}, "C", nil, score)

local autoOn = hs.settings.get("concise.auto") == true
local lastResult = nil
local menu = hs.menubar.new()

local function updateMenu()
  local title = autoOn and "ON" or "OFF"
  if autoOn and lastResult then title = title .. " " .. lastResult end
  menu:setTitle(title)
end

-- Auto-check only listens while one of these apps is in front (bundle IDs). The hotkey works everywhere.
local AUTO_APPS = {["com.microsoft.VSCode"] = true, ["com.apple.Notes"] = true}

local DRY_RUN = false
local MAX_BUF = 1000
local PAUSE = 1.5
local ABBREV = {["e.g."] = true, ["i.e."] = true, ["etc."] = true, ["vs."] = true,
  ["mr."] = true, ["mrs."] = true, ["ms."] = true, ["dr."] = true}
local END = {["."] = true, ["?"] = true, ["!"] = true}
local CLOSERS = {['"'] = true, ["'"] = true, [")"] = true, ["]"] = true, ["”"] = true, ["’"] = true, ["»"] = true}
local CLEAR_KEYS = {}
for _, k in ipairs({"tab", "escape", "left", "right", "up", "down", "home", "end",
  "pageup", "pagedown", "forwarddelete"}) do
  CLEAR_KEYS[hs.keycodes.map[k]] = true
end
local KEY_RETURN, KEY_PADENTER, KEY_BACKSPACE = 36, 76, 51

local buf = ""
local pending = false
local inAllowedApp = false
local pauseTimer
local lastDownAlert = -60

local function clearBuf()
  buf = ""
  pending = false
  if pauseTimer then pauseTimer:stop() end
end

local function handleSentence(sentence)
  log(string.format("auto: sentence len=%d", #sentence))
  if DRY_RUN then
    hs.alert.show('"' .. sentence .. '"', 2)
    return
  end
  postSentence(sentence, function(r)
    showScore(r)
    lastResult = string.format("%s%.2f", r.good and "✓" or "✗", r.score)
    updateMenu()
  end, function()
    if os.time() - lastDownAlert >= 60 then
      lastDownAlert = os.time()
      hs.alert.show("concise server not running")
    end
  end)
end

-- Returns true if the pending end mark really ended a sentence (buffer is reset),
-- false if it was an abbreviation and the buffer should keep growing.
local function confirmEnd()
  pending = false
  if pauseTimer then pauseTimer:stop() end
  local sentence = buf:match("^%s*(.-)%s*$")
  local lastWord = (sentence:match("(%S+)$") or ""):lower():gsub("^[\"'(%[“‘«]+", ""):gsub("[\"')%]”’»]+$", "")
  if ABBREV[lastWord] then return false end
  buf = ""
  local _, words = sentence:gsub("%S+", "")
  if words >= 3 then handleSentence(sentence) end
  return true
end

pauseTimer = hs.timer.delayed.new(PAUSE, function()
  if pending then confirmEnd() end
end)

local function updateAllowedApp(app)
  inAllowedApp = app ~= nil and AUTO_APPS[app:bundleID() or ""] == true
end

local function onKey(e)
  if not inAllowedApp then return false end
  local flags = e:getFlags()
  local code = e:getKeyCode()
  -- Option+Backspace deletes a whole word, which the buffer can't mirror.
  if flags.cmd or flags.ctrl or CLEAR_KEYS[code] or (flags.alt and code == KEY_BACKSPACE) then
    clearBuf()
  elseif code == KEY_RETURN or code == KEY_PADENTER then
    if pending then confirmEnd() end
    clearBuf()
  elseif code == KEY_BACKSPACE then
    local last = utf8.offset(buf, -1)
    buf = last and buf:sub(1, last - 1) or ""
    pending = END[buf:sub(-1)] or false
    pauseTimer:stop()
  else
    local c = e:getCharacters() or ""
    if c == "" then return false end
    if pending and not END[c] and not CLOSERS[c] then
      if c:match("^%s$") and confirmEnd() then return false end
      pending = false
      pauseTimer:stop()
    end
    buf = buf .. c
    if #buf > MAX_BUF then buf = buf:sub(-MAX_BUF) end
    if END[c] then
      pending = true
      pauseTimer:start()
    end
  end
  return false
end

local keyTap = hs.eventtap.new({hs.eventtap.event.types.keyDown}, onKey)
local mouseTap = hs.eventtap.new({hs.eventtap.event.types.leftMouseDown}, function()
  clearBuf()
  return false
end)
-- Taps run only while auto-check is on and an allowed app is in front, so other apps' keys never reach us.
local function syncTaps()
  if autoOn and inAllowedApp then
    keyTap:start()
    mouseTap:start()
  else
    keyTap:stop()
    mouseTap:stop()
  end
end

local appWatcher = hs.application.watcher.new(function(_, event, app)
  if event == hs.application.watcher.activated then
    clearBuf()
    updateAllowedApp(app)
    syncTaps()
  end
end)

local function setAuto(on)
  autoOn = on
  hs.settings.set("concise.auto", on)
  clearBuf()
  updateAllowedApp(hs.application.frontmostApplication())
  if on then appWatcher:start() else appWatcher:stop() end
  syncTaps()
  updateMenu()
end

local function toggleAuto()
  setAuto(not autoOn)
  hs.alert.show("concise auto-check " .. (autoOn and "ON" or "OFF"))
end

menu:setTooltip("Concise auto-check in VS Code and Notes (Ctrl+Option+K)")
menu:setClickCallback(toggleAuto)
hs.hotkey.bind({"ctrl", "alt"}, "K", toggleAuto)
setAuto(autoOn)
