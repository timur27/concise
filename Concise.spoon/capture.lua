-- Reads the current selection by posting Cmd+C, then restores the clipboard.
-- selection(cb) always calls back once: cb(text) or cb(nil, reason), reason one of "busy", "concealed", "empty".
local Capture = {}
Capture.__index = Capture

-- Password managers mark secrets with these types and clear them later; rewriting the clipboard would defeat that.
local CONCEALED = {"org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"}

function Capture.isConcealed(data)
  for _, uti in ipairs(CONCEALED) do
    if data[uti] ~= nil then return true end
  end
  return false
end

function Capture.new(opts)
  opts = opts or {}
  return setmetatable({
    pasteboard = opts.pasteboard or hs.pasteboard,
    eventtap = opts.eventtap or hs.eventtap,
    timer = opts.timer or hs.timer,
    log = opts.log or function() end,
    busy = false,
    pollTimer = nil,
  }, Capture)
end

-- Cmd+C is ignored while Ctrl/Option are still held, so poll (without blocking) until they are released.
function Capture:_whenModifiersUp(fn)
  local tries = 0
  self.pollTimer = self.timer.doEvery(0.02, function()
    tries = tries + 1
    local mods = self.eventtap.checkKeyboardModifiers()
    if not (mods.ctrl or mods.alt) or tries >= 50 then
      self.pollTimer:stop()
      fn(tries * 0.02)
    end
  end)
  self.pollTimer:fire()
end

function Capture:_copy(waited, finish)
  local pb = self.pasteboard
  local saved = pb.readAllData() or {}
  if Capture.isConcealed(saved) then
    self.log("copy: skipped, clipboard holds concealed data")
    return finish(nil, "concealed")
  end
  local before = pb.changeCount()
  self.log(string.format("copy: waited=%.2f changeCount=%d", waited, before))
  for _, down in ipairs({true, false}) do
    local e = self.eventtap.event.newKeyEvent("c", down)
    e:setFlags({cmd = true})
    e:post()
  end

  local tries = 0
  self.pollTimer = self.timer.doEvery(0.05, function()
    tries = tries + 1
    local changed = pb.changeCount() ~= before
    if not changed and tries < 20 then return end
    self.pollTimer:stop()
    local text = pb.getContents()
    self.log(string.format("copy: after %d tries changed=%s textlen=%d", tries, tostring(changed), text and #text or -1))
    if changed then
      if next(saved) then pb.writeAllData(saved) else pb.clearContents() end
    end
    if changed and text and text ~= "" then finish(text) else finish(nil, "empty") end
  end)
end

-- A second request while copying is refused, so the saved clipboard is always restored.
function Capture:selection(callback)
  if self.busy then return callback(nil, "busy") end
  self.busy = true
  local function finish(text, reason)
    self.busy = false
    callback(text, reason)
  end
  self:_whenModifiersUp(function(waited) self:_copy(waited, finish) end)
end

return Capture
